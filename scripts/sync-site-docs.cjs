#!/usr/bin/env node
// Generate the repository guides from the same structured source as /docs.
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const platform = process.argv[2];
if (!platform) throw new Error('Usage: node scripts/sync-site-docs.cjs /path/to/platform [--check] (install platform dependencies first)');
const root = path.resolve(__dirname, '..');
const source = path.resolve(platform);
const {articles} = require(path.join(source, 'apps/api/test/docs-load.cjs'));
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();
const base = 'https://bastionsecurity.io';
const href = value => value.startsWith('/docs') ? (value.replace(/^\/docs\/?/, '').split('#')[0] || 'overview') + '.md' + (value.includes('#') ? '#' + value.split('#')[1] : '') : value.startsWith('/') ? base + value : value;
function block(b) {
  switch (b.type) {
    case 'text': return b.text;
    case 'list': return b.items.map((item, i) => `${b.ordered ? i + 1 + '.' : '-'} ${item}`).join('\n');
    case 'note': return `> **${b.title}**\n>\n> ${b.text.replace(/\n/g, '\n> ')}`;
    case 'code': return b.examples.map(e => `${e.filename || e.label ? `**${e.filename || e.label}**\n\n` : ''}\`\`\`${e.language}\n${e.code}\n\`\`\``).join('\n\n');
    case 'table': return `| ${b.columns.join(' | ')} |\n| ${b.columns.map(() => '---').join(' | ')} |\n${b.rows.map(row => '| ' + row.map(cell => cell.replace(/\|/g, '\\|').replace(/\n/g, '<br>')).join(' | ') + ' |').join('\n')}`;
    case 'links': return b.items.map(item => `- [${item.title}](${href(item.href)}) — ${item.description}`).join('\n');
    default: throw new Error('Unknown docs block: ' + b.type);
  }
}
const files = new Map();
for (const a of articles) {
  const slug = a.slug || 'overview';
  files.set(`docs/${slug}.md`, `<!-- Generated by scripts/sync-site-docs.cjs; edit platform docs source. -->\n# ${a.title}\n\n${a.description}\n\nSource: [site documentation](${base}/docs${a.slug ? '/' + a.slug : ''}) · platform revision \`${revision}\`.\n\n${a.sections.map(s => `<a id="${s.id}"></a>\n\n## ${s.title}\n\n${s.blocks.map(block).join('\n\n')}`).join('\n\n')}\n`);
}
files.set('docs/README.md', `# Developer setup guides\n\nThese guides and code blocks are generated from the website's developer documentation at platform revision \`${revision}\`. The language-specific runnable entry point is [examples/README.md](../examples/README.md).\n\n${articles.map(a => `- [${a.title}](${a.slug || 'overview'}.md) — ${a.description}`).join('\n')}\n\nTo update after a platform docs change, install the platform checkout's dependencies and run from this SDK repository:\n\n\`\`\`sh\nnode scripts/sync-site-docs.cjs /path/to/platform\nnode scripts/sync-site-docs.cjs /path/to/platform --check\n\`\`\`\n\nThe generator also copies the complete PostgreSQL webhook receiver and the exact published server verification function. Review and commit regenerated files with the matching SDK changes.\n`);
const sdk = JSON.parse(fs.readFileSync(path.join(root, 'scripts/example-language.json'), 'utf8'));
const snippets = articles.find(a => a.slug === 'server-sdks').sections.find(s => s.id === 'verification').blocks.flatMap(b => b.examples || []);
const example = snippets.find(e => e.label === sdk.label);
if (!example) throw new Error('Published verification example missing for ' + sdk.label);
files.set(`examples/published/${example.filename}`, example.code + '\n');
for (const name of ['README.md', '.env.example', '.gitignore', 'package.json', 'package-lock.json', 'schema.sql', 'migrate.mjs', 'server.mjs', 'worker.mjs']) {
  files.set(`examples/webhook-receiver/${name}`, fs.readFileSync(path.join(source, 'apps/web/examples/webhook-receiver', name), 'utf8'));
}
let failed = false;
for (const [relative, content] of files) {
  const filename = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== content) { console.error('Out of sync: ' + relative); failed = true; }
  } else { fs.mkdirSync(path.dirname(filename), {recursive: true}); fs.writeFileSync(filename, content); }
}
if (failed) process.exit(1);
console.log(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} ${files.size} files against the published docs source.`);
